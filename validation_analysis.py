from __future__ import annotations

from dataclasses import dataclass
from math import isclose, isfinite
from typing import Final, Literal, TypeGuard

from experiment_artifacts import (
    ExperimentArtifactManifest,
    ExperimentArtifactStore,
    ExperimentRunResult,
)
from experiment_specifications import (
    ExperimentRunSpecification,
    ExperimentSpecification,
)

ValidationSeverity = Literal["error", "warning"]
ValidationCategory = Literal[
    "manifest",
    "coverage",
    "identity",
    "specification",
    "metrics",
    "solution",
    "convergence",
]

DEFAULT_CONVERGENCE_RELATIVE_TOLERANCE: Final[float] = 1e-9
DEFAULT_CONVERGENCE_ABSOLUTE_TOLERANCE: Final[float] = 1e-12


@dataclass(frozen=True, slots=True)
class ValidationIssue:
    """Describe one validation finding."""

    severity: ValidationSeverity
    category: ValidationCategory
    message: str
    run_id: str | None = None

    @property
    def is_error(self) -> bool:
        return self.severity == "error"

    @property
    def is_warning(self) -> bool:
        return self.severity == "warning"


@dataclass(frozen=True, slots=True)
class RunValidationSummary:
    """Summarize validation findings for one completed run."""

    run_id: str
    problem_name: str
    dimension: int
    seed: int
    best_value: float
    function_evaluations: int
    iterations: int
    elapsed_seconds: float
    error_count: int
    warning_count: int

    @property
    def is_valid(self) -> bool:
        return self.error_count == 0


@dataclass(frozen=True, slots=True)
class ValidationReport:
    """Contain the result of validating an experiment artifact store."""

    experiment_id: str
    expected_run_count: int
    completed_run_count: int
    missing_run_count: int
    invalid_run_count: int
    warning_count: int
    issues: tuple[ValidationIssue, ...]
    run_summaries: tuple[RunValidationSummary, ...]

    @property
    def error_count(self) -> int:
        return sum(issue.is_error for issue in self.issues)

    @property
    def is_valid(self) -> bool:
        return self.error_count == 0

    @property
    def has_warnings(self) -> bool:
        return self.warning_count > 0

    @property
    def valid_run_count(self) -> int:
        return self.completed_run_count - self.invalid_run_count

    @property
    def missing_run_ids(self) -> tuple[str, ...]:
        return tuple(
            issue.run_id
            for issue in self.issues
            if issue.category == "coverage"
            and issue.run_id is not None
            and "Missing completed run" in issue.message
        )

    @property
    def error_issues(self) -> tuple[ValidationIssue, ...]:
        return tuple(issue for issue in self.issues if issue.is_error)

    @property
    def warning_issues(self) -> tuple[ValidationIssue, ...]:
        return tuple(issue for issue in self.issues if issue.is_warning)


def validate_experiment(
    artifact_store: ExperimentArtifactStore,
    *,
    expected_experiment: ExperimentSpecification | None = None,
    relative_tolerance: float = DEFAULT_CONVERGENCE_RELATIVE_TOLERANCE,
    absolute_tolerance: float = DEFAULT_CONVERGENCE_ABSOLUTE_TOLERANCE,
) -> ValidationReport:
    """Validate an experiment's persisted metadata and completed results.

    When ``expected_experiment`` is supplied, the validation checks the exact
    deterministic run set generated by that specification. This detects
    missing and unexpected runs and checks every persisted run against its
    expected problem, dimension, seed, configuration, and termination policy.

    Without ``expected_experiment``, the validation is self-contained and
    checks the persisted manifest, completed-run count, run identities, result
    metrics, solutions, and convergence histories. Exact missing run IDs cannot
    be identified without the expected run specification.
    """
    _validate_tolerances(relative_tolerance, absolute_tolerance)

    issues: list[ValidationIssue] = []
    run_summaries: list[RunValidationSummary] = []

    try:
        manifest = artifact_store.load_manifest()
    except Exception as error:  # noqa: BLE001
        issues.append(
            ValidationIssue(
                severity="error",
                category="manifest",
                message=f"Unable to load experiment manifest: {error}",
            )
        )
        return ValidationReport(
            experiment_id="unknown",
            expected_run_count=0,
            completed_run_count=0,
            missing_run_count=0,
            invalid_run_count=0,
            warning_count=0,
            issues=tuple(issues),
            run_summaries=(),
        )

    issues.extend(_validate_manifest(manifest, expected_experiment))

    expected_run_specifications: dict[str, ExperimentRunSpecification] = {}
    if expected_experiment is not None:
        expected_run_specifications = {
            run_specification.run_id: run_specification
            for run_specification in expected_experiment.iter_run_specifications()
        }

        if len(expected_run_specifications) != manifest.expected_run_count:
            issues.append(
                ValidationIssue(
                    severity="error",
                    category="coverage",
                    message=(
                        "The supplied ExperimentSpecification generates "
                        f"{len(expected_run_specifications)} unique runs, but the "
                        f"manifest declares {manifest.expected_run_count}."
                    ),
                )
            )

    try:
        completed_run_ids = tuple(sorted(artifact_store.completed_run_ids()))
    except Exception as error:  # noqa: BLE001
        issues.append(
            ValidationIssue(
                severity="error",
                category="coverage",
                message=f"Unable to enumerate completed runs: {error}",
            )
        )
        completed_run_ids = ()

    completed_run_id_set = set(completed_run_ids)

    if len(completed_run_ids) != len(completed_run_id_set):
        issues.append(
            ValidationIssue(
                severity="error",
                category="coverage",
                message=(
                    "The artifact store returned duplicate completed run identifiers."
                ),
            )
        )

    if len(completed_run_ids) > manifest.expected_run_count:
        issues.append(
            ValidationIssue(
                severity="error",
                category="coverage",
                message=(
                    f"The artifact store contains {len(completed_run_ids)} completed "
                    f"runs, exceeding the expected {manifest.expected_run_count}."
                ),
            )
        )
    elif len(completed_run_ids) < manifest.expected_run_count:
        issues.append(
            ValidationIssue(
                severity="error",
                category="coverage",
                message=(
                    f"Only {len(completed_run_ids)} of the expected "
                    f"{manifest.expected_run_count} runs are completed. Exact missing "
                    "run IDs require the expected ExperimentSpecification."
                ),
            )
        )

    if expected_run_specifications:
        expected_run_ids = set(expected_run_specifications)

        for missing_run_id in sorted(expected_run_ids - completed_run_id_set):
            issues.append(
                ValidationIssue(
                    severity="error",
                    category="coverage",
                    message=f"Missing completed run: {missing_run_id}",
                    run_id=missing_run_id,
                )
            )

        for unexpected_run_id in sorted(completed_run_id_set - expected_run_ids):
            issues.append(
                ValidationIssue(
                    severity="error",
                    category="coverage",
                    message=f"Unexpected completed run: {unexpected_run_id}",
                    run_id=unexpected_run_id,
                )
            )

    for run_id in completed_run_ids:
        try:
            run_result = artifact_store.load_run_result(run_id)
        except Exception as error:  # noqa: BLE001
            issues.append(
                ValidationIssue(
                    severity="error",
                    category="identity",
                    message=f"Unable to load completed run result: {error}",
                    run_id=run_id,
                )
            )
            continue

        expected_run_specification = expected_run_specifications.get(run_id)
        run_issues = validate_run_result(
            run_result,
            expected_run_specification=expected_run_specification,
            expected_experiment_id=manifest.experiment_id,
            relative_tolerance=relative_tolerance,
            absolute_tolerance=absolute_tolerance,
        )
        issues.extend(run_issues)

        run_summaries.append(_create_run_validation_summary(run_result, run_issues))

    invalid_run_ids = {
        issue.run_id
        for issue in issues
        if issue.run_id is not None and issue.severity == "error"
    }
    missing_run_ids = {
        issue.run_id
        for issue in issues
        if issue.category == "coverage"
        and issue.run_id is not None
        and "Missing completed run" in issue.message
    }

    return ValidationReport(
        experiment_id=manifest.experiment_id,
        expected_run_count=manifest.expected_run_count,
        completed_run_count=len(completed_run_ids),
        missing_run_count=len(missing_run_ids),
        invalid_run_count=len(invalid_run_ids - missing_run_ids),
        warning_count=sum(issue.is_warning for issue in issues),
        issues=tuple(issues),
        run_summaries=tuple(run_summaries),
    )


def validate_run_result(
    run_result: ExperimentRunResult,
    *,
    expected_run_specification: ExperimentRunSpecification | None = None,
    expected_experiment_id: str | None = None,
    relative_tolerance: float = DEFAULT_CONVERGENCE_RELATIVE_TOLERANCE,
    absolute_tolerance: float = DEFAULT_CONVERGENCE_ABSOLUTE_TOLERANCE,
) -> tuple[ValidationIssue, ...]:
    """Validate one run result independently of an artifact store."""
    _validate_tolerances(relative_tolerance, absolute_tolerance)

    run_specification = run_result.run_specification
    run_id = run_specification.run_id
    issues: list[ValidationIssue] = []

    issues.extend(_validate_run_identity(run_specification, expected_experiment_id))
    issues.extend(
        _validate_run_specification_against_expected(
            run_specification,
            expected_run_specification,
            run_id,
        )
    )
    issues.extend(_validate_run_metrics(run_result))
    issues.extend(_validate_best_solution(run_result))
    issues.extend(
        _validate_convergence(
            run_result,
            relative_tolerance=relative_tolerance,
            absolute_tolerance=absolute_tolerance,
        )
    )

    return tuple(issues)


def create_validation_summary_table(
    validation_report: ValidationReport,
) -> tuple[dict[str, object], ...]:
    """Return run-level validation summaries in tabular form."""
    return tuple(
        {
            "run_id": summary.run_id,
            "problem": summary.problem_name,
            "dimension": summary.dimension,
            "seed": summary.seed,
            "best_value": summary.best_value,
            "function_evaluations": summary.function_evaluations,
            "iterations": summary.iterations,
            "elapsed_seconds": summary.elapsed_seconds,
            "error_count": summary.error_count,
            "warning_count": summary.warning_count,
            "is_valid": summary.is_valid,
        }
        for summary in validation_report.run_summaries
    )


def create_validation_issue_table(
    validation_report: ValidationReport,
) -> tuple[dict[str, object], ...]:
    """Return validation issues in tabular form."""
    return tuple(
        {
            "severity": issue.severity,
            "category": issue.category,
            "run_id": issue.run_id,
            "message": issue.message,
        }
        for issue in validation_report.issues
    )


def _validate_tolerances(
    relative_tolerance: float,
    absolute_tolerance: float,
) -> None:
    if not isfinite(relative_tolerance) or relative_tolerance < 0.0:
        raise ValueError("relative_tolerance must be finite and non-negative.")
    if not isfinite(absolute_tolerance) or absolute_tolerance < 0.0:
        raise ValueError("absolute_tolerance must be finite and non-negative.")


def _validate_manifest(
    manifest: ExperimentArtifactManifest,
    expected_experiment: ExperimentSpecification | None,
) -> tuple[ValidationIssue, ...]:
    issues: list[ValidationIssue] = []

    artifact_schema_version = manifest.artifact_schema_version
    if not _is_non_negative_integer(artifact_schema_version):
        issues.append(
            ValidationIssue(
                severity="error",
                category="manifest",
                message=(
                    "Manifest artifact_schema_version must be a non-negative integer."
                ),
            )
        )

    expected_run_count = manifest.expected_run_count
    if not _is_non_negative_integer(expected_run_count):
        issues.append(
            ValidationIssue(
                severity="error",
                category="manifest",
                message="Manifest expected_run_count must be a non-negative integer.",
            )
        )

    experiment_id = manifest.experiment_id
    if not isinstance(experiment_id, str) or not experiment_id:
        issues.append(
            ValidationIssue(
                severity="error",
                category="manifest",
                message="Manifest experiment_id must be a non-empty string.",
            )
        )

    experiment_name = manifest.experiment_name
    if not isinstance(experiment_name, str) or not experiment_name:
        issues.append(
            ValidationIssue(
                severity="error",
                category="manifest",
                message="Manifest experiment_name must be a non-empty string.",
            )
        )

    if expected_experiment is not None:
        if experiment_id != expected_experiment.experiment_id:
            issues.append(
                ValidationIssue(
                    severity="error",
                    category="identity",
                    message=(
                        "Manifest experiment_id does not match the supplied "
                        "ExperimentSpecification."
                    ),
                )
            )

        if experiment_name != expected_experiment.name:
            issues.append(
                ValidationIssue(
                    severity="error",
                    category="specification",
                    message=(
                        "Manifest experiment_name does not match the supplied "
                        "ExperimentSpecification.name."
                    ),
                )
            )

        if expected_experiment.configuration_count < 1:
            issues.append(
                ValidationIssue(
                    severity="error",
                    category="specification",
                    message="The supplied experiment contains no configurations.",
                )
            )

    return tuple(issues)


def _validate_run_identity(
    run_specification: ExperimentRunSpecification,
    expected_experiment_id: str | None,
) -> tuple[ValidationIssue, ...]:
    issues: list[ValidationIssue] = []
    run_id = run_specification.run_id

    if not isinstance(run_id, str) or not run_id:
        issues.append(
            ValidationIssue(
                severity="error",
                category="identity",
                message="Run specification has an empty or invalid run_id.",
                run_id=run_id if isinstance(run_id, str) else None,
            )
        )

    if (
        not isinstance(run_specification.experiment_id, str)
        or not run_specification.experiment_id
    ):
        issues.append(
            ValidationIssue(
                severity="error",
                category="identity",
                message="Run specification has an empty or invalid experiment_id.",
                run_id=run_id,
            )
        )
    elif expected_experiment_id is not None and (
        run_specification.experiment_id != expected_experiment_id
    ):
        issues.append(
            ValidationIssue(
                severity="error",
                category="identity",
                message="Run experiment_id does not match the artifact manifest.",
                run_id=run_id,
            )
        )

    if not _is_positive_integer(run_specification.dimension):
        issues.append(
            ValidationIssue(
                severity="error",
                category="specification",
                message="Run dimension must be a positive integer.",
                run_id=run_id,
            )
        )

    if not _is_integer(run_specification.seed):
        issues.append(
            ValidationIssue(
                severity="error",
                category="specification",
                message="Run seed must be an integer.",
                run_id=run_id,
            )
        )

    return tuple(issues)


def _validate_run_specification_against_expected(
    actual: ExperimentRunSpecification,
    expected: ExperimentRunSpecification | None,
    run_id: str,
) -> tuple[ValidationIssue, ...]:
    if expected is None:
        return ()

    issues: list[ValidationIssue] = []

    if actual.run_id != expected.run_id:
        issues.append(
            ValidationIssue(
                severity="error",
                category="identity",
                message="Persisted run ID does not match the expected run ID.",
                run_id=run_id,
            )
        )

    if actual.experiment_id != expected.experiment_id:
        issues.append(
            ValidationIssue(
                severity="error",
                category="identity",
                message="Run experiment_id does not match the expected specification.",
                run_id=run_id,
            )
        )

    if actual.seed != expected.seed:
        issues.append(
            ValidationIssue(
                severity="error",
                category="specification",
                message="Run seed does not match the expected specification.",
                run_id=run_id,
            )
        )

    if actual.dimension != expected.dimension:
        issues.append(
            ValidationIssue(
                severity="error",
                category="specification",
                message="Run dimension does not match the expected specification.",
                run_id=run_id,
            )
        )

    if actual.problem.identity() != expected.problem.identity():
        issues.append(
            ValidationIssue(
                severity="error",
                category="specification",
                message=(
                    "Run problem specification does not match the expected "
                    "specification."
                ),
                run_id=run_id,
            )
        )

    if actual.configuration_id != expected.configuration_id:
        issues.append(
            ValidationIssue(
                severity="error",
                category="specification",
                message=(
                    "Run algorithm configuration does not match the expected "
                    "configuration."
                ),
                run_id=run_id,
            )
        )

    if actual.termination.identity() != expected.termination.identity():
        issues.append(
            ValidationIssue(
                severity="error",
                category="specification",
                message=(
                    "Run termination specification does not match the expected "
                    "termination."
                ),
                run_id=run_id,
            )
        )

    return tuple(issues)


def _validate_run_metrics(
    run_result: ExperimentRunResult,
) -> tuple[ValidationIssue, ...]:
    run_specification = run_result.run_specification
    run_id = run_specification.run_id
    termination = run_specification.termination
    issues: list[ValidationIssue] = []

    if not _is_finite_real(run_result.best_value):
        issues.append(
            ValidationIssue(
                severity="error",
                category="metrics",
                message="best_value must be a finite real number.",
                run_id=run_id,
            )
        )

    if not _is_non_negative_integer(run_result.function_evaluations):
        issues.append(
            ValidationIssue(
                severity="error",
                category="metrics",
                message="function_evaluations must be a non-negative integer.",
                run_id=run_id,
            )
        )
    elif termination.max_evaluations is not None and (
        run_result.function_evaluations > termination.max_evaluations
    ):
        issues.append(
            ValidationIssue(
                severity="error",
                category="metrics",
                message="function_evaluations exceeds the configured max_evaluations.",
                run_id=run_id,
            )
        )

    if not _is_non_negative_integer(run_result.iterations):
        issues.append(
            ValidationIssue(
                severity="error",
                category="metrics",
                message="iterations must be a non-negative integer.",
                run_id=run_id,
            )
        )
    elif termination.max_iterations is not None and (
        run_result.iterations > termination.max_iterations
    ):
        issues.append(
            ValidationIssue(
                severity="error",
                category="metrics",
                message="iterations exceeds the configured max_iterations.",
                run_id=run_id,
            )
        )

    if not _is_finite_real(run_result.elapsed_seconds):
        issues.append(
            ValidationIssue(
                severity="error",
                category="metrics",
                message="elapsed_seconds must be a finite real number.",
                run_id=run_id,
            )
        )
    elif float(run_result.elapsed_seconds) < 0.0:
        issues.append(
            ValidationIssue(
                severity="error",
                category="metrics",
                message="elapsed_seconds cannot be negative.",
                run_id=run_id,
            )
        )

    return tuple(issues)


def _validate_best_solution(
    run_result: ExperimentRunResult,
) -> tuple[ValidationIssue, ...]:
    run_specification = run_result.run_specification
    run_id = run_specification.run_id
    solution = run_result.best_solution
    issues: list[ValidationIssue] = []

    try:
        solution_length = len(solution)
    except TypeError:
        issues.append(
            ValidationIssue(
                severity="error",
                category="solution",
                message="best_solution must be a finite sequence of coordinates.",
                run_id=run_id,
            )
        )
        return tuple(issues)

    if solution_length != run_specification.dimension:
        issues.append(
            ValidationIssue(
                severity="error",
                category="solution",
                message=(
                    "best_solution length does not match the run dimension: "
                    f"expected {run_specification.dimension}, got {solution_length}."
                ),
                run_id=run_id,
            )
        )

    for coordinate_index, coordinate in enumerate(solution):
        if not _is_finite_real(coordinate):
            issues.append(
                ValidationIssue(
                    severity="error",
                    category="solution",
                    message=(
                        "best_solution contains a non-finite or non-numeric "
                        f"coordinate at index {coordinate_index}."
                    ),
                    run_id=run_id,
                )
            )
            break

    return tuple(issues)


def _validate_convergence(
    run_result: ExperimentRunResult,
    *,
    relative_tolerance: float,
    absolute_tolerance: float,
) -> tuple[ValidationIssue, ...]:
    run_specification = run_result.run_specification
    run_id = run_specification.run_id
    termination = run_specification.termination
    optimization = run_specification.problem.optimization
    evaluations: tuple[int, ...] = tuple(
        int(evaluation) for evaluation in run_result.convergence_evaluations
    )
    values: tuple[float, ...] = tuple(
        float(value) for value in run_result.convergence_values
    )
    issues: list[ValidationIssue] = []

    if len(evaluations) != len(values):
        issues.append(
            ValidationIssue(
                severity="error",
                category="convergence",
                message=(
                    "convergence_evaluations and convergence_values must "
                    "have the same length."
                ),
                run_id=run_id,
            )
        )
        return tuple(issues)

    if not evaluations:
        issues.append(
            ValidationIssue(
                severity="error",
                category="convergence",
                message="Convergence history is empty.",
                run_id=run_id,
            )
        )
        return tuple(issues)

    previous_evaluation: int | None = None
    for evaluation in evaluations:
        if not _is_positive_integer(evaluation):
            issues.append(
                ValidationIssue(
                    severity="error",
                    category="convergence",
                    message="Convergence evaluations must be positive integers.",
                    run_id=run_id,
                )
            )
            break

        integer_evaluation = int(evaluation)
        if (
            previous_evaluation is not None
            and integer_evaluation <= previous_evaluation
        ):
            issues.append(
                ValidationIssue(
                    severity="error",
                    category="convergence",
                    message=(
                        "Convergence evaluation counts must be strictly increasing."
                    ),
                    run_id=run_id,
                )
            )
            break

        previous_evaluation = integer_evaluation

    for value in values:
        if not _is_finite_real(value):
            issues.append(
                ValidationIssue(
                    severity="error",
                    category="convergence",
                    message="Convergence values must all be finite real numbers.",
                    run_id=run_id,
                )
            )
            break

    final_function_evaluations = run_result.function_evaluations
    if (
        _is_non_negative_integer(final_function_evaluations)
        and _is_positive_integer(evaluations[-1])
        and int(evaluations[-1]) > int(final_function_evaluations)
    ):
        issues.append(
            ValidationIssue(
                severity="error",
                category="convergence",
                message=(
                    "The last convergence evaluation exceeds the reported "
                    "function_evaluations."
                ),
                run_id=run_id,
            )
        )

    if (
        termination.max_evaluations is not None
        and _is_positive_integer(evaluations[-1])
        and int(evaluations[-1]) > termination.max_evaluations
    ):
        issues.append(
            ValidationIssue(
                severity="error",
                category="convergence",
                message=("Convergence history exceeds the configured max_evaluations."),
                run_id=run_id,
            )
        )

    finite_values = all(_is_finite_real(value) for value in values)
    if len(values) >= 2 and finite_values:
        previous_value = float(values[0])
        for value in values[1:]:
            current_value = float(value)
            if optimization == "minimize":
                violated_direction = current_value > previous_value and not isclose(
                    current_value,
                    previous_value,
                    rel_tol=relative_tolerance,
                    abs_tol=absolute_tolerance,
                )
            else:
                violated_direction = current_value < previous_value and not isclose(
                    current_value,
                    previous_value,
                    rel_tol=relative_tolerance,
                    abs_tol=absolute_tolerance,
                )

            if violated_direction:
                issues.append(
                    ValidationIssue(
                        severity="error",
                        category="convergence",
                        message=(
                            "Convergence values violate the expected best-so-far "
                            f"direction for {optimization}."
                        ),
                        run_id=run_id,
                    )
                )
                break
            previous_value = current_value

    if _is_finite_real(run_result.best_value) and finite_values and values:
        final_value = float(values[-1])
        best_value = float(run_result.best_value)
        if not isclose(
            final_value,
            best_value,
            rel_tol=relative_tolerance,
            abs_tol=absolute_tolerance,
        ):
            issues.append(
                ValidationIssue(
                    severity="warning",
                    category="convergence",
                    message=(
                        "The final convergence value differs from best_value "
                        "beyond the configured tolerance."
                    ),
                    run_id=run_id,
                )
            )

    if _is_positive_integer(evaluations[0]) and int(evaluations[0]) > 1:
        issues.append(
            ValidationIssue(
                severity="warning",
                category="convergence",
                message=(
                    "The convergence history starts after the first function "
                    f"evaluation (first recorded evaluation: {evaluations[0]})."
                ),
                run_id=run_id,
            )
        )

    return tuple(issues)


def _create_run_validation_summary(
    run_result: ExperimentRunResult,
    issues: tuple[ValidationIssue, ...],
) -> RunValidationSummary:
    run_specification = run_result.run_specification
    run_errors = sum(issue.is_error for issue in issues)
    run_warnings = sum(issue.is_warning for issue in issues)

    return RunValidationSummary(
        run_id=run_specification.run_id,
        problem_name=run_specification.problem.name,
        dimension=run_specification.dimension,
        seed=run_specification.seed,
        best_value=float(run_result.best_value),
        function_evaluations=int(run_result.function_evaluations),
        iterations=int(run_result.iterations),
        elapsed_seconds=float(run_result.elapsed_seconds),
        error_count=run_errors,
        warning_count=run_warnings,
    )


def _is_integer(value: object) -> TypeGuard[int]:
    return isinstance(value, int) and not isinstance(value, bool)


def _is_non_negative_integer(value: object) -> bool:
    return _is_integer(value) and value >= 0


def _is_positive_integer(value: object) -> bool:
    return _is_integer(value) and value > 0


def _is_finite_real(value: object) -> TypeGuard[int | float]:
    return (
        isinstance(value, (int, float))
        and not isinstance(value, bool)
        and isfinite(float(value))
    )


